"""Produce a per-question review checklist for the 42-question held-out
draft, without labelling any question human-approved.

For each row in `evaluation/dataset/heldout_DRAFT.json`:
  - Executability check: compile + run gold_sql against the pinned demo DB
    (sqlite3 only, outside the plan pipeline), note runtime + row count.
  - Label integrity flags: answerability vs. gold_sql presence consistency;
    expected_decision vs. answerability consistency.
  - Difficulty + question_type echoed for scanning.
  - Freeform `human_notes` field left blank per row for the reviewer.

Writes `paper_evidence/heldout_review_checklist.md`.
"""
from __future__ import annotations

import json
import pathlib
import sqlite3
import sys
import time
from typing import Any, Dict, List

ROOT = pathlib.Path(__file__).resolve().parents[1]
DRAFT = ROOT / "evaluation/dataset/heldout_DRAFT.json"
DB = ROOT / "backend/data/insightflow.db"
OUT = ROOT / "paper_evidence/heldout_review_checklist.md"


def run_sql(sql: str) -> Dict[str, Any]:
    try:
        t0 = time.perf_counter()
        with sqlite3.connect(str(DB)) as c:
            rows = c.execute(sql).fetchall()
        return {"ok": True, "n_rows": len(rows),
                "ms": int((time.perf_counter() - t0) * 1000),
                "sample": [list(r) for r in rows[:3]]}
    except Exception as e:
        return {"ok": False, "error": str(e)}


def check_row(row: dict) -> Dict[str, Any]:
    ans = row.get("answerability")
    gold = row.get("gold_sql") or ""
    exp_dec = row.get("expected_decision")
    flags: List[str] = []

    # Consistency: answerable row must have a gold_sql
    if ans == "answerable" and not gold:
        flags.append("MISSING: answerable row has no gold_sql")
    # Non-answerable rows shouldn't carry a gold_sql
    if ans in ("ambiguous", "out_of_scope") and gold:
        flags.append("INCONSISTENT: non-answerable row has a gold_sql")
    # Decision alignment
    if ans == "answerable" and exp_dec not in ("ANSWER", "WARN"):
        flags.append(f"DECISION: answerable + expected_decision={exp_dec}")
    if ans in ("ambiguous", "out_of_scope") and exp_dec not in (
            "CLARIFY", "ABSTAIN"):
        flags.append(f"DECISION: non-answerable + "
                      f"expected_decision={exp_dec}")

    exec_report = run_sql(gold) if gold else {"ok": None,
                                               "note": "no SQL to run"}
    # If gold executes but yields 0 rows on an answerable question, flag it
    if ans == "answerable" and exec_report.get("ok") \
            and exec_report.get("n_rows") == 0:
        flags.append("EMPTY: gold_sql returns 0 rows against pinned DB")

    return {"qid": row["question_id"],
            "question": row["natural_language_question"],
            "answerability": ans,
            "question_type": row.get("question_type"),
            "difficulty": row.get("difficulty"),
            "expected_decision": exp_dec,
            "gold_sql": gold,
            "exec": exec_report,
            "flags": flags}


def main() -> None:
    data = json.load(DRAFT.open())
    qs = data["questions"]
    rows = [check_row(q) for q in qs]

    lines = [
        "# Held-out review checklist (42 drafts)",
        "",
        "**Status:** DRAFT — not human-approved.  Do NOT quote any",
        "metric computed from this file as a held-out result until every",
        "row below has been reviewed and the `human_review` column is",
        "ticked.",
        "",
        "**Build date:** regenerated by `evaluation/build_heldout_checklist.py`",
        "**DB used for executability check:** pinned seed on",
        "`backend/data/insightflow.db`.",
        "",
        "## Per-question status",
        "",
        "| QID | Question | Ans | Decision | SQL compiles? | n rows | Flags | human_review |",
        "|---|---|---|---|:---:|---:|---|:---:|"
    ]
    for r in rows:
        ex = r["exec"]
        compiles = "—" if ex.get("ok") is None else (
            "YES" if ex.get("ok") else "NO")
        n_rows = (str(ex.get("n_rows"))
                  if ex.get("n_rows") is not None else
                  (ex.get("error", "")[:40] if not ex.get("ok") else "—"))
        flags = "<br>".join(r["flags"]) if r["flags"] else "none"
        q = r["question"].replace("|", "\\|")
        lines.append(f"| {r['qid']} | {q} | {r['answerability']} | "
                     f"{r['expected_decision']} | {compiles} | {n_rows} | "
                     f"{flags} | ☐ |")

    lines.append("")
    lines.append("## Summary")
    lines.append("")
    import collections
    n = len(rows)
    compile_ok = sum(1 for r in rows if r["exec"].get("ok"))
    compile_fail = sum(1 for r in rows if r["exec"].get("ok") is False)
    no_sql = sum(1 for r in rows if r["exec"].get("ok") is None)
    with_flags = sum(1 for r in rows if r["flags"])
    lines.append(f"- Total: **{n}** questions.")
    lines.append(f"- `gold_sql` compiles against pinned DB: "
                 f"**{compile_ok} / {n}** rows.")
    lines.append(f"- `gold_sql` compile FAILED: **{compile_fail} / {n}** rows.")
    lines.append(f"- Rows without `gold_sql` (ambiguous / out_of_scope): "
                 f"**{no_sql} / {n}** rows.")
    lines.append(f"- Rows flagged by at least one integrity check: "
                 f"**{with_flags} / {n}** rows.")
    lines.append("")
    lines.append("## Human-reviewer worksheet")
    lines.append("")
    lines.append("For each question above, verify (and tick"
                 " `human_review` only when all four hold):")
    lines.append("")
    lines.append("1. **SQL correctness.** Does `gold_sql` actually compute the")
    lines.append("   answer the natural-language question asks for? Catch:")
    lines.append("   wrong aggregation, wrong filter, wrong grouping, missing")
    lines.append("   join, off-by-one date boundaries.")
    lines.append("2. **Answerability label.** `answerable` only if the data")
    lines.append("   can answer it with no reasonable other interpretation.")
    lines.append("   Pick `ambiguous` when the question could mean multiple")
    lines.append("   things on the data, `out_of_scope` when the data cannot")
    lines.append("   answer it at all.")
    lines.append("3. **Decision alignment.** `answerable` → ANSWER (or WARN);")
    lines.append("   `ambiguous`/`out_of_scope` → CLARIFY (or ABSTAIN).")
    lines.append("4. **Difficulty + question_type.** Sanity-check these.")
    lines.append("")
    lines.append("Only after the box is ticked AND the file is renamed to")
    lines.append("`heldout_REVIEWED.json` (strip the DRAFT marker) may its")
    lines.append("rows be used as held-out evidence. The current paper must")
    lines.append("not quote any metric computed from `heldout_DRAFT.json`.")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} with {len(rows)} rows "
          f"({compile_ok} SQL ok, {compile_fail} SQL fail, {no_sql} no SQL, "
          f"{with_flags} flagged)")


if __name__ == "__main__":
    main()
