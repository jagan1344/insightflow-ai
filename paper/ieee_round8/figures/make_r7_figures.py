"""Fig. 5 (Round 7 ablation): data extracted from research_improvement/03_ablation_results.csv
(committed results of the frozen build 38b60d1). Writes data/round7_ablation.csv, a matplotlib
render fig_r7_ablation.pdf (grayscale, Liberation Serif = Times metrics, 3.45 in), and the
PGFPlots source src/fig_r7_ablation.tex in the style of src/common.tex."""
import csv, pathlib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

H = pathlib.Path(__file__).resolve().parent
SRC = H.parents[2] / "research_improvement" / "03_ablation_results.csv"
rows = {r["config"]: r for r in csv.DictReader(open(SRC))}
SHOW = [("A0", "Full pipeline (A0)"), ("A1", "Semantic layer off (A1)"),
        ("A5", "Coverage + wording checks off (A5)"), ("A7", "All six safeguards off (A7)"),
        ("B1", "Only semantic layer on (B1)"), ("B5", "Only coverage + wording on (B5)")]
MEAS = [("correct", "Correct answers (of 74 answerable)"), ("wrong_answers", "Wrong answers (of 105 questions)"),
        ("unnecessary_clarify", "Unnecessary clarifications (of 74 answerable)")]
with open(H / "data" / "round7_ablation.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["config", "label"] + [m for m, _ in MEAS])
    for k, lab in SHOW:
        w.writerow([k, lab] + [rows[k][m] for m, _ in MEAS])

plt.rcParams.update({"font.family": "Liberation Serif", "font.size": 7.5, "pdf.fonttype": 42, "hatch.linewidth": 0.5})
fig, ax = plt.subplots(figsize=(3.45, 2.55))
h = 0.26
styles = [dict(color="0.55", edgecolor="black"), dict(color="white", edgecolor="black", hatch="////"),
          dict(color="0.88", edgecolor="black")]
for j, (m, name) in enumerate(MEAS):
    ys = [i + (j - 1) * h for i in range(len(SHOW))]
    vals = [int(rows[k][m]) for k, _ in SHOW]
    ax.barh(ys, vals, h, label=name, linewidth=0.5, **styles[j])
    for y, v in zip(ys, vals):
        ax.text(v + 0.8, y, str(v), va="center", fontsize=6.5)
ax.set_yticks(range(len(SHOW))); ax.set_yticklabels([lab for _, lab in SHOW]); ax.invert_yaxis()
ax.set_xlim(0, 66); ax.set_xlabel("Questions (same 105-question set, frozen build 38b60d1)")
ax.grid(axis="x", color="0.85", lw=0.4); ax.set_axisbelow(True)
for s in ("top", "right"): ax.spines[s].set_visible(False)
ax.legend(fontsize=6.5, frameon=False, loc="upper center", bbox_to_anchor=(0.35, -0.2), ncol=1)
fig.savefig(H / "fig_r7_ablation.pdf", bbox_inches="tight")

coords = lambda m: " ".join(f"({rows[k][m]},{k})[{rows[k][m]}]" for k, _ in SHOW)
labels = ",".join("{" + lab + "}" for _, lab in SHOW)
(H / "src" / "fig_r7_ablation.tex").write_text(rf"""% Fig. 5  Round 7 ablation (single column, 3.45 in). Data: ../data/round7_ablation.csv,
% from research_improvement/03_ablation_results.csv (frozen build 38b60d1). Generated by ../make_r7_figures.py.
\documentclass[border=2pt]{{standalone}}
\input{{common.tex}}
\usepackage{{pgfplots}}
\pgfplotsset{{compat=1.17}}
\begin{{document}}
\begin{{tikzpicture}}
\begin{{axis}}[
  width=1.85in, height=2.0in, scale only axis=true,
  xbar=0.5pt, bar width=4.2pt, xmin=0, xmax=66,
  xlabel={{Questions (105-question set, frozen build \texttt{{38b60d1}})}},
  xlabel style={{font=\fontsize{{7.5}}{{8.6}}\selectfont}},
  ytick=data, y dir=reverse, symbolic y coords={{{",".join(k for k, _ in SHOW)}}},
  yticklabels={{{labels}}},
  yticklabel style={{align=right,font=\fontsize{{7}}{{8}}\selectfont,text width=1.2in}},
  xticklabel style={{font=\fontsize{{7.5}}{{8.6}}\selectfont}},
  enlarge y limits=0.1, axis x line*=bottom, axis y line*=left, xmajorgrids, grid style={{gray!25}},
  nodes near coords, nodes near coords style={{font=\fontsize{{6.5}}{{7.5}}\selectfont,anchor=west}},
  point meta=explicit symbolic,
  legend style={{font=\fontsize{{7}}{{8}}\selectfont,at={{(0.3,-0.22)}},anchor=north,legend columns=1,draw=none,cells={{anchor=west}}}},
]
\addplot[draw=black,fill=gray!55] coordinates {{{coords("correct")}}};
\addplot[draw=black,pattern=north east lines] coordinates {{{coords("wrong_answers")}}};
\addplot[draw=black,fill=gray!12] coordinates {{{coords("unnecessary_clarify")}}};
\legend{{{{Correct answers (of 74 answerable)}},{{Wrong answers (of 105 questions)}},{{Unnecessary clarifications (of 74 answerable)}}}}
\end{{axis}}
\end{{tikzpicture}}
\end{{document}}
""")
print(open(H / "data" / "round7_ablation.csv").read())
